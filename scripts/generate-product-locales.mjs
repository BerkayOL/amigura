function block(lang) {
  const lines = PRODUCTS.map((p) => {
    const d = p[lang];
    return `    "${p.slug}": {
      "name": ${JSON.stringify(d.name)},
      "desc": ${JSON.stringify(d.desc)},
      "price": ${JSON.stringify(d.price)},
      "careWash": ${JSON.stringify(d.careWash)},
      "careSize": ${JSON.stringify(d.careSize)},
      "careSafety": ${JSON.stringify(d.careSafety)}
    }`;
  });
  return lines.join(",\n");
}

function wizardBlock(lang) {
  const key = lang === "tr" ? "wizardTr" : "wizardEn";
  return PRODUCTS.map((p) => `    "${p.slug}": ${JSON.stringify(p[key])}`).join(",\n");
}

const out = {
  productsTr: block("tr"),
  productsEn: block("en"),
  wizardTr: wizardBlock("tr"),
  wizardEn: wizardBlock("en"),
};

fs.writeFileSync(path.join(__dirname, "product-locales.generated.json"), JSON.stringify(out, null, 2));
